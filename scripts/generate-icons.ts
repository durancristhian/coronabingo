/* eslint-disable @typescript-eslint/no-var-requires */
const { readdirSync, readFileSync, writeFileSync } = require('fs')
const { join } = require('path')

// Turns the SVGs built by draw-icons in design/icons/ into React components.
// See design/icons/README.md for the full workflow.
const iconsDir = join(__dirname, '../design/icons')
const outputFile = join(__dirname, '../components/icons/index.tsx')
const rootAttributes: Record<string, string> = {
  fill: 'none',
  stroke: 'currentColor',
  'stroke-linecap': 'round',
  'stroke-linejoin': 'round',
  'stroke-width': '2',
  viewBox: '0 0 24 24',
}

const readAttributes = (source: string) =>
  Array.from(source.matchAll(/([\w-]+)="([^"]*)"/g)).reduce<
    Record<string, string>
  >((attributes, [, name, value]) => ({ ...attributes, [name]: value }), {})

const toComponentName = (fileName: string) =>
  fileName
    .replace(/\.svg$/, '')
    .split('-')
    .map(part => part[0].toUpperCase() + part.slice(1))
    .join('') + 'Icon'

const icons = readdirSync(iconsDir)
  .filter((fileName: string) => fileName.endsWith('.svg'))
  .sort()
  .map((fileName: string) => {
    const svg: string = readFileSync(join(iconsDir, fileName), 'utf8')
    const root = svg.match(/<svg([^>]*)>/)
    if (!root) throw new Error(`${fileName} has no <svg> element`)

    const attributes = readAttributes(root[1])
    for (const [name, value] of Object.entries(rootAttributes)) {
      if (attributes[name] !== value) {
        throw new Error(
          `${fileName}: expected ${name}="${value}", got "${attributes[name]}". ` +
            'Update rootAttributes and IconBase when the icon DNA changes.',
        )
      }
    }

    const elements = Array.from(
      svg.matchAll(
        /<(path|circle|rect|line|polyline|polygon|ellipse)([^>]*)\/>/g,
      ),
    ).map(([, tag, elementAttributes]) => {
      const props = Object.entries(readAttributes(elementAttributes))
        .map(([name, value]) => `${name}="${value}"`)
        .join(' ')

      return `      <${tag} ${props} />`
    })
    if (!elements.length) throw new Error(`${fileName} has no shapes`)

    return [
      `export function ${toComponentName(fileName)}(props: IconProps) {`,
      '  return (',
      '    <IconBase {...props}>',
      ...elements,
      '    </IconBase>',
      '  )',
      '}',
    ].join('\n')
  })

const output = `// Generated by \`npm run generate-icons\` from design/icons/*.svg. Do not edit.
import React, { SVGProps } from 'react'

type IconProps = SVGProps<SVGSVGElement>

function IconBase(props: IconProps) {
  return (
    <svg
      aria-hidden="true"
      fill="none"
      focusable="false"
      height="1em"
      stroke="currentColor"
      strokeLinecap="round"
      strokeLinejoin="round"
      strokeWidth={2}
      viewBox="0 0 24 24"
      width="1em"
      xmlns="http://www.w3.org/2000/svg"
      {...props}
    />
  )
}

${icons.join('\n\n')}
`

writeFileSync(outputFile, output)
console.log(`Wrote ${icons.length} icons to ${outputFile}`)
